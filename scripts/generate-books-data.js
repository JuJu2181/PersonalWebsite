// Regenerates js/books-data.js from data/books.json.
//
// data/books.json is the CMS-editable source of truth (see admin/config.yml).
// Run this after editing books.json by hand, or via the deploy workflow.

const fs = require('fs');
const path = require('path');

const INPUT_PATH = path.join(__dirname, '..', 'data', 'books.json');
const OUTPUT_PATH = path.join(__dirname, '..', 'js', 'books-data.js');

function main() {
  const { current, past } = JSON.parse(fs.readFileSync(INPUT_PATH, 'utf8'));

  const withSlots = (books, prefix) =>
    books.map((book, i) => ({ ...book, slotId: prefix === 'book-current' ? prefix : `${prefix}-${i + 1}` }));

  const currentBooks = withSlots(current, 'book-current');
  const pastBooks = withSlots(past, 'book-past');

  const output = `// Generated by scripts/generate-books-data.js from data/books.json
// Do not edit by hand — edit data/books.json (or via the CMS at /admin) and re-run.

const CURRENT_BOOKS = ${JSON.stringify(currentBooks, null, 2)};

const PAST_BOOKS = ${JSON.stringify(pastBooks, null, 2)};
`;

  fs.writeFileSync(OUTPUT_PATH, output);
  console.log(`Wrote ${currentBooks.length} current + ${pastBooks.length} past books to ${OUTPUT_PATH}`);
}

main();
