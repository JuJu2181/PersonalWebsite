// Regenerates js/blog-data.js from the Hashnode RSS feed.
//
// Why a build-time script instead of a runtime fetch in the browser:
// Hashnode's RSS feed does not send CORS headers, so a browser fetch()
// from a different origin than the blog is blocked. Fetching it here in
// Node sidesteps that entirely and keeps the deployed site a plain static
// site with no runtime dependency on a third-party CORS proxy.
//
// Run this whenever a new post is published:
//   node scripts/fetch-blog-posts.js

const fs = require('fs');
const path = require('path');

const RSS_URL = 'https://anish-shilpakar.com.np/rss.xml';
const POST_COUNT = 3;
const EXCERPT_LENGTH = 150;
const OUTPUT_PATH = path.join(__dirname, '..', 'js', 'blog-data.js');

function field(itemBlock, tag) {
  const cdata = itemBlock.match(new RegExp(`<${tag}><!\\[CDATA\\[([\\s\\S]*?)\\]\\]></${tag}>`));
  if (cdata) return cdata[1].trim();
  const plain = itemBlock.match(new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`));
  return plain ? plain[1].trim() : '';
}

function cleanExcerpt(raw) {
  const collapsed = raw.replace(/\s+/g, ' ').trim();
  if (collapsed.length <= EXCERPT_LENGTH) return collapsed;
  const cut = collapsed.slice(0, EXCERPT_LENGTH);
  const lastSpace = cut.lastIndexOf(' ');
  return `${cut.slice(0, lastSpace)}…`;
}

function formatDate(pubDate) {
  const d = new Date(pubDate);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-US', { month: 'short', year: 'numeric' });
}

async function main() {
  const res = await fetch(RSS_URL);
  if (!res.ok) throw new Error(`RSS fetch failed: ${res.status} ${res.statusText}`);
  const xml = await res.text();

  const items = [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)]
    .map(m => m[1])
    .slice(0, POST_COUNT)
    .map(block => ({
      title: field(block, 'title'),
      excerpt: cleanExcerpt(field(block, 'description')),
      href: field(block, 'link'),
      date: formatDate(field(block, 'pubDate'))
    }));

  if (!items.length) throw new Error('No posts found in RSS feed');

  const output = `// Generated by scripts/fetch-blog-posts.js from ${RSS_URL}
// Do not edit by hand — re-run the script to refresh (see comment there for why).
// Last generated: ${new Date().toISOString()}

const BLOG_POSTS = ${JSON.stringify(items, null, 2)};
`;

  fs.writeFileSync(OUTPUT_PATH, output);
  console.log(`Wrote ${items.length} posts to ${OUTPUT_PATH}`);
}

main().catch(err => {
  console.error(err.message);
  process.exit(1);
});
